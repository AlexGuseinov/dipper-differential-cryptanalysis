#!/usr/bin/env python3
"""Writes src/bs_const.h: the bitsliced index maps of bitslice.h (BS_ROTSRC, BS_PDST)
as compile-time constants for rotation constants (1, 4, 7, 11), so that the compiler
resolves rotations and the bit permutation to register renaming.
longdiff checks these tables against bs_init() at start."""
ROT = (1, 4, 7, 11)
rotsrc = [0] * 64
for w in range(4):
    base, r = 48 - 16 * w, ROT[w]
    for k in range(16):
        rotsrc[base + ((k + r) & 15)] = base + k
def perm_bit(i):
    return 4 * (i // 16) + 16 * ((3 * ((i % 16) // 4) + (i % 4)) % 4) + (i % 4)
pdst = [perm_bit(i) for i in range(64)]
fmt = lambda a: ", ".join(map(str, a))
print("/* generated by src/gen_bs_const.py; rotation constants 1, 4, 7, 11 */")
print("#ifndef BS_CONST_H\n#define BS_CONST_H")
print(f"static const int BSC_ROT[4] = {{{fmt(ROT)}}};")
print(f"static const int BSC_ROTSRC[64] = {{{fmt(rotsrc)}}};")
print(f"static const int BSC_PDST[64] = {{{fmt(pdst)}}};")
print("#endif")
